// Правка фикстуры: три проспекта через плазы + rationale в notes. Временный файл.
import { readFileSync, writeFileSync } from 'node:fs';
const path = 'probe/open-2km.json';
const raw = JSON.parse(readFileSync(path, 'utf8'));
raw.roads = JSON.parse(readFileSync('.tmp/avenues.json', 'utf8'));
raw.metadata.notes = [
  'Цена сборки этого брифа — строка «2 км²» в таблице § 2.6 плана открытого мира.',
  'Правка плотности кварталов или радиуса петли меняет её, поэтому числа фикстуры',
  'авторские и не наследуются из главы 13.',
  '',
  'Три проспекта в `roads` — правка данных, а не скелета (решение владельца по § 7.1',
  'п. 5): кварталы генератора стоят на своих террасах, а межквартальные плазы в 100–160',
  'м ничем не заняты, и на естественном поле соседние ярусы расходятся глубже шага ноги',
  '— скелет давал 4 компоненты с вердиктом `step` на каждом стыке. Проспект ведёт от',
  'торца улицы одного района к торцу другого, концы лежат ровно на этих торцах (сварка',
  'нулевой длины), середина — по собранному полю с террасами и площадками (`fieldAt +',
  'streetRise` шагом ~24 м), худший уклон 0,051 м/м при пределе 0,3. Без них «одна сеть',
  'мира» была бы обещанием алгоритму там, где бриф обещает только кварталы.',
].join('\n');
writeFileSync(path, JSON.stringify(raw, null, 2).replace(/\n/g, '\r\n'));
console.log('записано, roads =', raw.roads.length);
