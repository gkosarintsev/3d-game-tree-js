import { readFileSync } from 'node:fs';
import { expandCity } from '../tools/city.js';
import { normalizeLevel } from '../tools/normalize-level.mjs';
const raw = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const map = normalizeLevel(expandCity(structuredClone(raw))).map;
const byType = {};
for (const r of map.roads) byType[r.type] = (byType[r.type] ?? 0) + 1;
console.log('roads by type', JSON.stringify(byType));
const g = map.roads.find(r => r.type === 'ground');
const b = map.roads.find(r => r.type !== 'ground');
console.log('ground road keys', g && Object.keys(g), g && JSON.stringify({ ...g, decks: g.decks?.slice(0, 2) }, null, 1).slice(0, 900));
console.log('other road keys', b && Object.keys(b), b && JSON.stringify({ ...b, decks: b.decks?.slice(0, 1) }, null, 1).slice(0, 900));
console.log('channels', JSON.stringify((map.channels ?? []).slice(0, 2), null, 1).slice(0, 1200));
const bd = map.buildings.find(x => x.doors?.length);
console.log('door', JSON.stringify(bd?.doors?.[0], null, 1));
console.log('building keys', bd && Object.keys(bd));
